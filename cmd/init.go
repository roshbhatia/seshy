const fishIntegration = `# seshy shell integration — generated by sy init fish
function sy
  if test (count $argv) -eq 1; and not string match -q -- '-*' $argv[1]
    switch $argv[1]
      case {{ join .Reserved " " }}
        command sy $argv
        return
    end
    set -l _p (command sy --greedy $argv[1] 2>/dev/null)
    if test -n "$_p"
      cd $_p
      return
    end
  end
  command sy $argv
end
`

const nushellBody = ` {
  if $greedy != null {
    return (^sy --greedy $greedy ...$args)
  }
  if (($args | length) == 1) and (not ($args.0 | str starts-with "-")) and ($args.0 not-in [{{ quote .Reserved }}]) {
    let resolved = (^sy --greedy $args.0 | complete)
    if ($resolved.exit_code == 0) and (not ($resolved.stdout | str trim | is-empty)) {
      cd ($resolved.stdout | str trim)
      return
    }
  }
  ^sy ...$args
}
`

type integrationData struct {
	Reserved []string
}

func renderShellIntegration(name, source string) (string, error) {
	tmpl, err := template.New(name).Funcs(template.FuncMap{
		"join":  strings.Join,
		"quote": quoteNushellValues,
	}).Parse(source)
	if err != nil {
		return "", err
	}
	var output bytes.Buffer
	if err := tmpl.Execute(&output, integrationData{Reserved: rootInvocationNames()}); err != nil {
		return "", err
	}
	return output.String(), nil
}

func rootInvocationNames() []string {
	seen := map[string]struct{}{}
	for _, command := range rootCmd.Commands() {
		seen[command.Name()] = struct{}{}
		for _, alias := range command.Aliases {
			seen[alias] = struct{}{}
		}
	}
	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func quoteNushellValues(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = fmt.Sprintf("%q", value)
	}
	return strings.Join(quoted, " ")
}

func init() {
	rootCmd.AddCommand(initCmd)
}
