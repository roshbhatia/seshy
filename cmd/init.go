var initCmd = &cobra.Command{
	Use:   "init <shell>",
	Short: "Print shell integration code",
	Long: `Print shell integration code for your shell.

Add to your shell config:
  eval "$(sy init zsh)"   # zsh
  eval "$(sy init bash)"  # bash
  sy init fish | source   # fish
  sy init nu | save --force ~/.config/nushell/vendor/autoload/sy.nu

With shell integration active, "sy <name>" will cd into the session directory
using greedy matching. Commands and aliases always run as commands. Use
"sy --greedy <name>" to resolve a session whose name conflicts with one.`,
	Args:      cobra.ExactArgs(1),
	ValidArgs: []string{"zsh", "bash", "fish", "nu"},
	RunE: func(cmd *cobra.Command, args []string) error {
		switch args[0] {
		case "fish":
			generated, err := renderShellIntegration("fish", fishIntegration)
			if err != nil {
				return err
			}
			fmt.Print(generated)
		case "nu":
			generated, err := generatedCompletion("nu")
			if err != nil {
				return err
			}
			fmt.Println(generated)
		case "zsh", "bash":
			generated, err := renderShellIntegration(args[0], map[string]string{
				"zsh":  zshIntegration,
				"bash": bashIntegration,
			}[args[0]])
			if err != nil {
				return err
			}
			fmt.Print(generated)
		default:
			return fmt.Errorf("unsupported shell %q — supported: zsh, bash, fish, nu", args[0])
		}
		return nil
	},
}

const zshIntegration = `# seshy shell integration — generated by sy init zsh
function sy() {
  local _p
  if [[ $# -eq 1 ]] && [[ "${1}" != -* ]]; then
    case "${1}" in
      {{ join .Reserved "|" }}) command sy "$@"; return ;;
    esac
    if _p=$(command sy --greedy "${1}" 2>/dev/null) && [[ -n "${_p}" ]]; then
      cd "${_p}"
      return
    fi
  fi
  command sy "$@"
}
`

